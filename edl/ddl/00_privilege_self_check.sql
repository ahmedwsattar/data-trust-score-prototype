-- ===========================================================================
-- SECTION C — Cross-role gap analysis (run after A and B in same session)
-- ===========================================================================

-- ## Cell C1 — Side-by-side PASS/FAIL comparison
SELECT
    COALESCE(d.CHECK_NAME, a.CHECK_NAME)              AS CHECK_NAME,
    d.RESULT                                          AS PNC_DEVELOPER_RL_RESULT,
    d.DETAIL                                          AS PNC_DEVELOPER_RL_DETAIL,
    a.RESULT                                          AS PNC_AIML_DEVELOPER_RL_RESULT,
    a.DETAIL                                          AS PNC_AIML_DEVELOPER_RL_DETAIL,
    CASE
        WHEN d.RESULT = a.RESULT THEN 'ALIGNED'
        WHEN d.RESULT IN ('PASS', 'INFO') AND a.RESULT IN ('FAIL', 'WARN') THEN 'AIML_GAP'
        WHEN a.RESULT IN ('PASS', 'INFO') AND d.RESULT IN ('FAIL', 'WARN') THEN 'DEVELOPER_GAP'
        ELSE 'MIXED'
    END                                               AS GAP_SIGNAL
FROM PRIVILEGE_CHECK_PNC_DEVELOPER d
FULL OUTER JOIN PRIVILEGE_CHECK_PNC_AIML a
    ON d.CHECK_NAME = a.CHECK_NAME
ORDER BY GAP_SIGNAL DESC, CHECK_NAME;

-- ## Cell C2 — Checks that likely need a DBA grant (any role FAIL on DMF/Cortex/CREATE)
SELECT ROLE_NAME, SECTION, CHECK_NAME, RESULT, DETAIL
FROM (
    SELECT * FROM PRIVILEGE_CHECK_PNC_DEVELOPER
    UNION ALL
    SELECT * FROM PRIVILEGE_CHECK_PNC_AIML
) u
WHERE RESULT IN ('FAIL', 'WARN')
  AND SECTION ILIKE ANY ('%DMF%', '%Cortex%', '%CREATE%')
ORDER BY ROLE_NAME, CHECK_NAME;
