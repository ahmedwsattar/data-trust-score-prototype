-- Read-only privilege introspection for EDLE-DEV before committing to a
-- governance layout, native-DMF wiring, or Streamlit deploy. Avoids
-- SNOWFLAKE.ACCOUNT_USAGE (not readable to PNC roles) and avoids bare
-- DECLARE/BEGIN at worksheet top level — each check is plain SQL + SHOW +
-- RESULT_SCAN(LAST_QUERY_ID()).
--
-- HOW TO RUN (Snowsight worksheet or Notebook)
-- --------------------------------------------
-- Option A — one session, two role passes:
--   1. Run Section A (all cells) as PNC_DEVELOPER_RL.
--   2. USE ROLE PNC_AIML_DEVELOPER_RL; run Section B (all cells).
--   3. Run Section C (gap analysis) — both temp tables must exist.
-- Option B — split into Notebook cells at each `-- ## Cell N` banner.
--
-- Copy Section C output back to the build conversation.
-------------------------------------------------------------------------------

