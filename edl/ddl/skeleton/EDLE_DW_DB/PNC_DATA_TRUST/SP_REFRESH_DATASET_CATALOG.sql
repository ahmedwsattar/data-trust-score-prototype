-- Target: main/DDL/EDLE_DW_DB/PNC_DATA_TRUST/SP_REFRESH_DATASET_CATALOG.sql
--
-- Discovers scoreable tables from INFORMATION_SCHEMA and MERGEs into
-- PNC_DATASET_CATALOG so stewards don't hand-maintain FQNs.
-------------------------------------------------------------------------------

USE ROLE PNC_DEVELOPER_RL;
USE DATABASE EDLE_DW_DB;
USE SCHEMA PNC_DATA_TRUST;
USE WAREHOUSE PNC_AIML_WH;

CREATE OR REPLACE PROCEDURE EDLE_DW_DB.PNC_DATA_TRUST.SP_REFRESH_DATASET_CATALOG(
    P_TABLE_CATALOG STRING DEFAULT 'EDLE_DW_DB',
    P_TABLE_SCHEMA  STRING DEFAULT 'PNC_DATA',
    P_NAME_PATTERN  STRING DEFAULT 'DT_%'
)
RETURNS STRING
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    v_rows NUMBER;
BEGIN
    MERGE INTO EDLE_DW_DB.PNC_DATA_TRUST.PNC_DATASET_CATALOG t
    USING (
        SELECT
            'DS_' || REPLACE(TABLE_NAME, 'DT_', '')           AS DATASET_ID,
            REPLACE(TABLE_NAME, '_', ' ')                     AS DATASET_NAME,
            TABLE_CATALOG || '.' || TABLE_SCHEMA || '.' || TABLE_NAME AS DATASET_FQN,
            TABLE_CATALOG,
            TABLE_SCHEMA,
            TABLE_NAME,
            TABLE_TYPE,
            ROW_COUNT
        FROM IDENTIFIER(:P_TABLE_CATALOG || '.INFORMATION_SCHEMA.TABLES')
        WHERE TABLE_SCHEMA = :P_TABLE_SCHEMA
          AND TABLE_TYPE = 'BASE TABLE'
          AND TABLE_NAME LIKE :P_NAME_PATTERN
    ) s
    ON t.DATASET_FQN = s.DATASET_FQN
    WHEN MATCHED THEN UPDATE SET
        ROW_COUNT = s.ROW_COUNT,
        LAST_REFRESHED_AT = CURRENT_TIMESTAMP(),
        UPDATED_BY = CURRENT_USER()
    WHEN NOT MATCHED THEN INSERT (
        DATASET_ID, DATASET_NAME, DATASET_FQN,
        TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE, ROW_COUNT,
        IS_SCORE_ENABLED, LAST_REFRESHED_AT, UPDATED_BY
    ) VALUES (
        s.DATASET_ID, s.DATASET_NAME, s.DATASET_FQN,
        s.TABLE_CATALOG, s.TABLE_SCHEMA, s.TABLE_NAME, s.TABLE_TYPE, s.ROW_COUNT,
        TRUE, CURRENT_TIMESTAMP(), CURRENT_USER()
    );

    v_rows := SQLROWCOUNT;
    RETURN 'Merged rows: ' || v_rows::STRING;
END;
$$;

